export type Gender = 'MALE' | 'FEMALE';

interface Pronouns {
    له: string;
    ه: string;
    عنه: string;
    نزله: string;
    مدخله: string;
    كان: string;
    محسنا: string;
    مسيئا: string;
    حسناته: string;
    سيئاته: string;
}

const getPronounsForGender = (gender: Gender): Pronouns => {
    if (gender === 'MALE') {
        return {
            له: 'له',
            ه: 'ه',
            عنه: 'عنه',
            نزله: 'نُزله',
            مدخله: 'مدخله',
            كان: 'كان',
            محسنا: 'محسناً',
            مسيئا: 'مسيئاً',
            حسناته: 'حسناته',
            سيئاته: 'سيئاته',
        };
    } else {
        return {
            له: 'لها',
            ه: 'ها',
            عنه: 'عنها',
            نزله: 'نُزلها',
            مدخله: 'مدخلها',
            كان: 'كانت',
            محسنا: 'محسنة',
            مسيئا: 'مسيئة',
            حسناته: 'حسناتها',
            سيئاته: 'سيئاتها',
        };
    }
};

export const getDuaText = (gender: Gender): string[] => {
    const p = getPronounsForGender(gender);

    return [
        `اللهم اغفر ${p.له} وارحمه، وعافه واعفُ ${p.عنه}، وأكرم ${p.نزله}، ووسّع ${p.مدخله}، واغسله بالماء والثلج والبرد، ونقِّه من الخطايا كما يُنقَّى الثوب الأبيض من الدنس`,

        `اللهمّ أبدله داراً خيراً من داره، وأهلاً خيراً من أهله، وعملاً خيرا من عمله، وأدخله الجنّة، وأعذه من عذاب القبر، ومن عذاب النّار`,

        `اللهمّ عامله بما أنت أهله، ولا تعامله بما هو أهله`,

        `اللهمّ اجزه عن الإحسان إحساناً، وعن الإساءة عفواً وغفراناً`,

        `اللهمّ إن ${p.كان} ${p.محسنا} فزد من ${p.حسناته}، وإن ${p.كان} ${p.مسيئا} فتجاوز عن ${p.سيئاته}`,

        `اللهمّ أدخله الجنّة من غير حساب ولا سابقة عذاب`,

        `اللهمّ آنسه في وحدته، وفي وحشته، وفي غربته`,

        `اللهمّ أنزله منزلاً مباركاً، وأنت خير المنزلين`,

        `اللهمّ أنزله منازل الصدّيقين، والشّهداء، والصّالحين، وحسُن أولئك رفيقاً`,

        `اللهمّ اجعل قبره روضةً من رياض الجنّة، ولا تجعله حفرةً من حفر النّار`,

        `اللهم اجعل هذا الذكر صدقة جارية في ميزان حسناته، وكل من قرأه فاجعل له مثل الأجر`,
    ];
};

